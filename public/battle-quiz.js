export function shuffled(items, random = Math.random) {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

export function createPythonQuiz(previousIds = []) {
  const previous = new Set(previousIds);
  const fresh = shuffled(pythonQuestions.filter(q => !previous.has(q.id)));
  const rest = shuffled(pythonQuestions.filter(q => previous.has(q.id)));
  return shuffled([...fresh, ...rest].slice(0, 20)).map(q => {
    const options = shuffled(q.options.map((text, index) => ({text, correct:index === q.answer})));
    return {...q, options:options.map(o => o.text), answer:options.findIndex(o => o.correct)};
  });
}
